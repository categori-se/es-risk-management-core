const issue = (id, topic, label, scrutiny, reason, screeningQuestions, evidence, sourceIds) =>
  ({id, topic, label, scrutiny, reason, screeningQuestions, evidence, sourceIds});

function profile(id, name, description, subsectors, sourceKeys, issues) {
  return {id, name, description, subsectors,
    sources: sourceKeys.map(key => ({id: `${id}:${key}`, title: sources[key][0], url: sources[key][1]})),
    issues: issues.map(value => {
      const [ifcRefs, wbRefs, adbRefs] = topicStandards[value.topic];
      return {...value, id: `${id}.${value.id}`, sourceIds: value.sourceIds.map(key => `${id}:${key}`),
        standardRefs: {ifc_ps_2012: [...ifcRefs], wb_esf_2016: [...wbRefs], adb_esf_2024: [...adbRefs]}};
    })};
}

function freeze(value) {
  if (value && typeof value === "object" && !Object.isFrozen(value)) {
    Object.values(value).forEach(freeze);
    Object.freeze(value);
  }
  return value;
}

